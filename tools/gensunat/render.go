package main

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"
)

const header = "// Code generated by tools/gensunat. DO NOT EDIT.\n" +
	"// Edit catalogs/*.json and re-run `npm run gen` in perunio-sunat-catalogs.\n\n"

// renderDoc produces the package documentation, listing what the package holds
// so `go doc github.com/nmitic/perunio-sunat-catalogs/sunat` is useful on its own.
func renderDoc(catalogs []*catalog) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("// Package sunat holds the SUNAT catálogos as constants, lookup tables and\n")
	b.WriteString("// predicates, generated from the JSON in this repository.\n//\n")
	b.WriteString("// Codes are plain strings throughout. Go has no literal-union type, so a defined\n")
	b.WriteString("// string type would buy no compile-time safety while forcing a conversion at\n")
	b.WriteString("// every JSON, database and XML boundary.\n//\n")
	b.WriteString("// Catálogos in this package:\n//\n")
	for _, c := range catalogs {
		num := "perunio-internal"
		if c.SunatCatalog != nil {
			num = "Cat." + *c.SunatCatalog
		}
		fmt.Fprintf(&b, "//\t%-10s %-16s %s (%d entries)\n", c.ID, num, c.Name, len(c.Entries))
	}
	b.WriteString("package sunat\n")
	return gofmt(&b)
}

// renderCatalog produces one catalog's constants, entry table and accessors.
func renderCatalog(c *catalog) ([]byte, error) {
	p := pascal(c.ID)     // Cat16
	v := unexported(c.ID) // cat16
	// title heads the const block; short is what inline doc comments repeat, so
	// they stay readable ("one Cat.16 code", not "one Cat.16 — Tipo de … code").
	title, short := c.Name, c.Name
	if c.SunatCatalog != nil {
		title = fmt.Sprintf("Cat.%s — %s", *c.SunatCatalog, c.Name)
		short = "Cat." + *c.SunatCatalog
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package sunat\n\n")

	if c.goNames() {
		fmt.Fprintf(&b, "// %s.\n//\n// Source: %s\nconst (\n", title, c.Source)
		for _, e := range c.Entries {
			fmt.Fprintf(&b, "\t// %s\n\t%s%s = %s\n", e.Description, p, e.GoName, strconv.Quote(e.Code))
		}
		b.WriteString(")\n\n")
	} else {
		fmt.Fprintf(&b, "// %s.\n//\n// Source: %s\n//\n// This catalog sets goConsts:false — too large for one named constant per\n// entry. Use the lookup functions below.\n\n", title, c.Source)
	}

	fmt.Fprintf(&b, "// %sEntry describes one %s code.\ntype %sEntry struct {\n", p, short, p)
	b.WriteString("\tCode        string\n\tLabel       string\n\tDescription string\n")
	for _, k := range c.flagKeys {
		fmt.Fprintf(&b, "\t%s bool\n", pascalKey(k))
	}
	for _, k := range c.propKeys {
		fmt.Fprintf(&b, "\t%s %s\n", pascalKey(k), goPropType(c, k))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// %sCodes lists every %s code, in catálogo order.\nvar %sCodes = []string{\n", p, short, p)
	for _, e := range c.Entries {
		fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(e.Code))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "var %s = map[string]%sEntry{\n", v, p)
	for _, e := range c.Entries {
		fmt.Fprintf(&b, "\t%s: {Code: %s, Label: %s, Description: %s",
			strconv.Quote(e.Code), strconv.Quote(e.Code), strconv.Quote(e.Label), strconv.Quote(e.Description))
		for _, k := range c.flagKeys {
			fmt.Fprintf(&b, ", %s: %t", pascalKey(k), e.Flags[k])
		}
		for _, k := range c.propKeys {
			fmt.Fprintf(&b, ", %s: %s", pascalKey(k), goPropValue(c, k, e.Props[k]))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// %s returns the entry for code and whether it is a known %s code.\n", p, short)
	fmt.Fprintf(&b, "func %s(code string) (%sEntry, bool) {\n\te, ok := %s[code]\n\treturn e, ok\n}\n\n", p, p, v)

	fmt.Fprintf(&b, "// %sValid reports whether code is a known %s code.\n", p, short)
	fmt.Fprintf(&b, "func %sValid(code string) bool {\n\t_, ok := %s[code]\n\treturn ok\n}\n", p, v)

	for _, cap := range c.caps {
		codes := codesWithCapability(c, cap)
		name := p + pascalKey(cap)
		fmt.Fprintf(&b, "\n// %sCodes lists the %s codes with the %q capability.\nvar %sCodes = []string{\n", name, short, cap, name)
		for _, code := range codes {
			fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(code))
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "var %sSet = map[string]struct{}{\n", unexportedFirst(name))
		for _, code := range codes {
			fmt.Fprintf(&b, "\t%s: {},\n", strconv.Quote(code))
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "// %s reports whether code has the %q capability: %s\n", name, cap, capabilityDoc(cap))
		fmt.Fprintf(&b, "func %s(code string) bool {\n\t_, ok := %sSet[code]\n\treturn ok\n}\n", name, unexportedFirst(name))
	}

	for _, k := range c.flagKeys {
		fmt.Fprintf(&b, "\n// %s%s reports the %s flag for code. False for unknown codes.\n", p, pascalKey(k), k)
		fmt.Fprintf(&b, "func %s%s(code string) bool {\n\treturn %s[code].%s\n}\n", p, pascalKey(k), v, pascalKey(k))
	}

	for _, k := range c.propKeys {
		zero := "the zero value"
		if goPropType(c, k) == "string" {
			zero = `""`
		}
		fmt.Fprintf(&b, "\n// %s%s returns the %s of code, or %s if the code is unknown.\n", p, pascalKey(k), k, zero)
		fmt.Fprintf(&b, "func %s%s(code string) %s {\n\treturn %s[code].%s\n}\n", p, pascalKey(k), goPropType(c, k), v, pascalKey(k))
	}

	return gofmt(&b)
}

func codesWithCapability(c *catalog, cap string) []string {
	var out []string
	for _, e := range c.Entries {
		for _, got := range e.Capabilities {
			if got == cap {
				out = append(out, e.Code)
				break
			}
		}
	}
	return out
}

// capabilityDoc keeps the generated comment one short line; meta/capabilities.json
// is the full reference.
func capabilityDoc(cap string) string {
	switch cap {
	case "emit":
		return "the facturador may put it on the wire."
	case "select":
		return "the issuance UI may offer it."
	case "download":
		return "a CPE of this type is retrievable from consultacpe."
	case "void":
		return "it may appear in a Comunicación de Baja."
	case "retired":
		return "SUNAT withdrew it; display only, never emit."
	case "internal":
		return "it is a Perunio marker that never reaches the wire."
	default:
		return "see meta/capabilities.json."
	}
}

// goPropType picks the Go type for a prop. Cross-catalog references are codes, so
// they are strings; otherwise the type follows the values actually present.
func goPropType(c *catalog, key string) string {
	if _, ok := c.PropRefs[key]; ok {
		return "string"
	}
	var hasString, hasNumber, hasBool bool
	for _, e := range c.Entries {
		switch e.Props[key].(type) {
		case string:
			hasString = true
		case float64:
			hasNumber = true
		case bool:
			hasBool = true
		}
	}
	switch {
	case hasString:
		return "string"
	case hasNumber:
		return "float64"
	case hasBool:
		return "bool"
	default:
		return "string" // every value is null
	}
}

// goPropValue renders a prop as a Go literal. JSON null becomes the zero value:
// Go has no natural union, and the zero value is what every accessor already
// returns for an unknown code.
func goPropValue(c *catalog, key string, v any) string {
	switch goPropType(c, key) {
	case "float64":
		if n, ok := v.(float64); ok {
			return strconv.FormatFloat(n, 'g', -1, 64)
		}
		return "0"
	case "bool":
		if b, ok := v.(bool); ok {
			return strconv.FormatBool(b)
		}
		return "false"
	default:
		if s, ok := v.(string); ok {
			return strconv.Quote(s)
		}
		return `""`
	}
}

// pascal converts a catalog id to its exported prefix: cat16 -> Cat16,
// estado-ruc -> EstadoRuc.
func pascal(id string) string {
	var b strings.Builder
	for _, part := range strings.Split(id, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

// unexported converts a catalog id to its package-private name: cat16 -> cat16,
// estado-ruc -> estadoRuc.
func unexported(id string) string {
	return unexportedFirst(pascal(id))
}

func unexportedFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// pascalKey converts a flag, prop or capability name to an exported field name:
// referencial -> Referencial, afectoIGV -> AfectoIGV, on-boleta -> OnBoleta.
func pascalKey(key string) string {
	var b strings.Builder
	for _, part := range strings.Split(key, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}
