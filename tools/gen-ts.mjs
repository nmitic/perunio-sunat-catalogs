#!/usr/bin/env node
// Emits gen/ts/<id>.js and gen/ts/<id>.d.ts for every catalog, plus the package
// `exports` map. JavaScript and declarations are written side by side rather than
// TypeScript on purpose: it removes any build step from this repo, and it lets
// perunio-backend consume the package without touching its tsconfig, whose
// rootDir ("./src") makes a .ts import from outside src/ a TS6059 error.
//
// Usage:  node tools/gen-ts.mjs [--check]
//   --check  render into memory and diff against disk; exit 1 on any difference.

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { load, SpecError, REPO_ROOT } from './spec.mjs'

const OUT_DIR = join(REPO_ROOT, 'gen/ts')
const HEADER = [
  '// Code generated by tools/gen-ts.mjs. DO NOT EDIT.',
  '// Edit catalogs/*.json and re-run `npm run gen` in perunio-sunat-catalogs.',
  '',
].join('\n')

const lit = (v) => JSON.stringify(v)
const screaming = (id) => id.toUpperCase().replace(/-/g, '_')
const pascal = (id) => id.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')
const constCase = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()

/** Fields flattened onto every entry object, in a stable order. */
function fields(cat) {
  return [
    ...cat.flagKeys.map((k) => ({ key: k, kind: 'flag' })),
    ...cat.propKeys.map((k) => ({ key: k, kind: 'prop' })),
  ]
}

function tsTypeForProp(cat, key) {
  const ref = cat.propRefs[key]
  if (ref) return `${pascal(ref)}Code`
  // Union of the value types actually present, so a prop that is always a number
  // types as number rather than a catch-all.
  const seen = new Set(cat.entries.map((e) => (e.props[key] === null ? 'null' : typeof e.props[key])))
  return [...seen].sort().join(' | ')
}

function subsets(cat) {
  // `display` is every code, which is already CAT<N>_CODES — emitting it again
  // would be noise.
  const out = []
  for (const [cap, codes] of Object.entries(cat.capabilityCodes)) {
    if (cap === 'display') continue
    out.push({ name: constCase(cap.replace(/-/g, '_')), codes, type: true })
  }
  for (const [flag, codes] of Object.entries(cat.flagCodes)) {
    out.push({ name: constCase(flag), codes, type: false })
  }
  return out
}

function renderJs(cat) {
  const C = screaming(cat.id)
  const P = pascal(cat.id)
  const f = fields(cat)
  const out = [HEADER]

  out.push(`/** ${cat.name}${cat.sunatCatalog ? ` — SUNAT catálogo ${cat.sunatCatalog}` : ''}. */`)
  out.push(`export const ${C}_CODES = [${cat.codes.map(lit).join(', ')}];`, '')

  out.push(`export const ${C} = {`)
  for (const e of cat.entries) {
    const parts = [`code: ${lit(e.code)}`, `label: ${lit(e.label)}`, `description: ${lit(e.description)}`]
    for (const { key, kind } of f) parts.push(`${key}: ${lit(kind === 'flag' ? e.flags[key] : e.props[key])}`)
    out.push(`  ${lit(e.code)}: { ${parts.join(', ')} },`)
  }
  out.push('};', '')

  out.push(`/** Every entry, in catálogo order. Same object identities as ${C}. */`)
  out.push(`export const ${C}_ENTRIES = [${cat.codes.map((c) => `${C}[${lit(c)}]`).join(', ')}];`, '')

  out.push(`export function is${P}Code(value) {`)
  out.push(`  return ${C}_CODES.includes(value);`)
  out.push('}', '')
  out.push(`/** Entry for an untrusted string, or undefined. */`)
  out.push(`export function ${cat.id.replace(/-(.)/g, (_, c) => c.toUpperCase())}(value) {`)
  out.push(`  return is${P}Code(value) ? ${C}[value] : undefined;`)
  out.push('}')

  for (const s of subsets(cat)) {
    out.push('', `export const ${C}_${s.name}_CODES = [${s.codes.map(lit).join(', ')}];`)
    if (s.type) {
      out.push(`export const ${C}_${s.name}_ENTRIES = [${s.codes.map((c) => `${C}[${lit(c)}]`).join(', ')}];`)
      out.push(`export function is${P}${pascal(s.name.toLowerCase())}Code(value) {`)
      out.push(`  return ${C}_${s.name}_CODES.includes(value);`)
      out.push('}')
    }
  }

  for (const key of cat.propKeys) {
    out.push('', `/** ${cat.name} → ${key}. */`)
    out.push(`export const ${C}_${constCase(key)} = {`)
    for (const e of cat.entries) out.push(`  ${lit(e.code)}: ${lit(e.props[key])},`)
    out.push('};')
  }

  return out.join('\n') + '\n'
}

function renderDts(cat) {
  const C = screaming(cat.id)
  const P = pascal(cat.id)
  const f = fields(cat)
  const out = [HEADER]

  const imports = [...new Set(Object.values(cat.propRefs))].sort()
  for (const ref of imports) {
    out.push(`import type { ${pascal(ref)}Code } from './${ref}.js';`)
  }
  if (imports.length) out.push('')

  out.push(`/** ${cat.name}${cat.sunatCatalog ? ` — SUNAT catálogo ${cat.sunatCatalog}` : ''}. */`)
  out.push(`export declare const ${C}_CODES: readonly [${cat.codes.map(lit).join(', ')}];`)
  out.push(`export type ${P}Code = (typeof ${C}_CODES)[number];`, '')

  out.push(`export interface ${P}Entry {`)
  out.push(`  readonly code: ${P}Code;`)
  out.push('  readonly label: string;')
  out.push('  readonly description: string;')
  for (const { key, kind } of f) {
    out.push(`  readonly ${key}: ${kind === 'flag' ? 'boolean' : tsTypeForProp(cat, key)};`)
  }
  out.push('}', '')

  // Record over a literal union is a mapped type, not an index signature, so
  // noUncheckedIndexedAccess adds no `| undefined` and
  // noPropertyAccessFromIndexSignature never fires.
  out.push(`export declare const ${C}: Readonly<Record<${P}Code, ${P}Entry>>;`)
  out.push(`export declare const ${C}_ENTRIES: readonly ${P}Entry[];`, '')
  out.push(`export declare function is${P}Code(value: string): value is ${P}Code;`)
  out.push(`/** Entry for an untrusted string, or undefined. */`)
  out.push(
    `export declare function ${cat.id.replace(/-(.)/g, (_, c) => c.toUpperCase())}(value: string): ${P}Entry | undefined;`,
  )

  for (const s of subsets(cat)) {
    out.push('', `export declare const ${C}_${s.name}_CODES: readonly [${s.codes.map(lit).join(', ')}];`)
    if (s.type) {
      const sub = `${P}${pascal(s.name.toLowerCase())}Code`
      out.push(`export type ${sub} = (typeof ${C}_${s.name}_CODES)[number];`)
      out.push(`export declare const ${C}_${s.name}_ENTRIES: readonly ${P}Entry[];`)
      out.push(`export declare function is${P}${pascal(s.name.toLowerCase())}Code(value: string): value is ${sub};`)
    }
  }

  for (const key of cat.propKeys) {
    out.push('', `/** ${cat.name} → ${key}. */`)
    out.push(`export declare const ${C}_${constCase(key)}: Readonly<Record<${P}Code, ${tsTypeForProp(cat, key)}>>;`)
  }

  return out.join('\n') + '\n'
}

function renderPackageJson(catalogs) {
  const path = join(REPO_ROOT, 'package.json')
  const pkg = JSON.parse(readFileSync(path, 'utf8'))
  pkg.exports = Object.fromEntries(
    catalogs.map((c) => [`./${c.id}`, { types: `./gen/ts/${c.id}.d.ts`, default: `./gen/ts/${c.id}.js` }]),
  )
  return JSON.stringify(pkg, null, 2) + '\n'
}

// ── main ──────────────────────────────────────────────────────────────────────

const check = process.argv.includes('--check')
let catalogs
try {
  ;({ catalogs } = load())
} catch (err) {
  if (err instanceof SpecError) {
    console.error(err.message)
    process.exit(1)
  }
  throw err
}

const rendered = new Map()
for (const cat of catalogs) {
  rendered.set(join(OUT_DIR, `${cat.id}.js`), renderJs(cat))
  rendered.set(join(OUT_DIR, `${cat.id}.d.ts`), renderDts(cat))
}
rendered.set(join(REPO_ROOT, 'package.json'), renderPackageJson(catalogs))

mkdirSync(OUT_DIR, { recursive: true })

const expected = new Set([...rendered.keys()].map((p) => p.replace(`${OUT_DIR}/`, '')))
const orphans = readdirSync(OUT_DIR).filter((f) => !expected.has(f))

if (check) {
  const problems = []
  for (const [path, want] of rendered) {
    let got
    try {
      got = readFileSync(path, 'utf8')
    } catch {
      problems.push(`${path}: missing`)
      continue
    }
    if (got !== want) {
      const g = got.split('\n')
      const w = want.split('\n')
      const i = g.findIndex((line, n) => line !== w[n])
      problems.push(`${path}: differs at line ${i + 1}\n      on disk: ${g[i]}\n      expected: ${w[i]}`)
    }
  }
  for (const f of orphans) problems.push(`gen/ts/${f}: not produced by the generator — delete it`)
  if (problems.length) {
    console.error(`generated output is stale:\n  ${problems.join('\n  ')}\n\nRun: npm run gen`)
    process.exit(1)
  }
  console.log(`ok — ${rendered.size} generated file(s) match the spec`)
} else {
  let written = 0
  for (const [path, content] of rendered) {
    // Only touch files that changed, so mtimes stay stable for incremental tsc.
    let got = null
    try {
      got = readFileSync(path, 'utf8')
    } catch {}
    if (got !== content) {
      writeFileSync(path, content)
      written++
    }
  }
  for (const f of orphans) console.warn(`warning: gen/ts/${f} is not produced by the generator — delete it`)
  console.log(`ok — ${rendered.size} file(s), ${written} written`)
}
